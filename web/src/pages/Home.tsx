import { useEffect, useState } from 'react'
import { Link } from 'react-router-dom'

import { Nav } from '@/components/site/Nav'
import { Segmented } from '@/components/site/Segmented'
import { Sheet } from '@/components/site/Sheet'
import { Button } from '@/components/ui/button'
import { Select, SelectContent, SelectGroup, SelectItem, SelectLabel, SelectTrigger, SelectValue } from '@/components/ui/select'
import evidence from '@/data/evidence.json'
import { type Finding, type Level, LEVELS, isInstruction } from '@/lib/scanner'
import { cn } from '@/lib/utils'

// Everything shown here is generated by scanner/build_home_specimens.py from the real scanner and results/.
interface Specimen {
  key: string
  label: string
  verdict: Level
  finding: Finding
  measured: { n: number; detected: number } | null
  crop: { image: string; width: number; height: number; top: number } | null
}
interface Ablation { columns: string[]; rows: { key: string; cells: { s: number; n: number }[] }[] }
type View = 'person' | 'program'

const hero = evidence.hero as unknown as { image: string; width: number; height: number; seconds: number; findings: Finding[]; lines?: number[][] }
const specimens = evidence.specimens as unknown as Specimen[]
const { experiment, evaluation } = evidence
const ablation = (experiment as unknown as { ablation?: Ablation }).ablation

const VIEWS: { id: View; label: string }[] = [{ id: 'person', label: 'As a person sees it' }, { id: 'program', label: 'As a program reads it' }]
const LEVEL_TEXT: Record<Level, string> = { attack: 'text-attack', review: 'text-review', clean: 'text-clean' }
const wrap = 'mx-auto w-full max-w-[1240px] px-5 md:px-8'
const lede = 'mt-5 max-w-[58ch] text-[19px] leading-relaxed text-graphite'
const h2 = 'title text-[clamp(2rem,3.4vw,2.75rem)]'
const pct = (n: number, of: number) => `${Math.round((1000 * n) / of) / 10}%`

/* ------------------------------------------------------------------ opening */

const heroMarks = hero.findings.map((finding, i) => ({ finding, number: i + 1 }))
const SWEEP_MS = (hero.lines?.length ?? 0) * 22 + 700

function Hero() {
  // The one piece of motion on the page: the page is shown as printed, then selected line by line.
  const still = typeof window !== 'undefined' && window.matchMedia('(prefers-reduced-motion: reduce)').matches
  const [view, setView] = useState<View>(still ? 'program' : 'person')
  const [sweep, setSweep] = useState(!still)
  useEffect(() => {
    if (still) return
    const start = setTimeout(() => setView('program'), 1100)
    const end = setTimeout(() => setSweep(false), 1100 + SWEEP_MS)
    return () => { clearTimeout(start); clearTimeout(end) }
  }, [still])
  const choose = (v: View) => { setSweep(false); setView(v) }
  const program = view === 'program'

  return (
    <section className={cn(wrap, 'grid items-start gap-x-12 gap-y-12 pb-20 pt-12 md:pt-16 lg:grid-cols-[minmax(0,4.7fr)_minmax(0,7.3fr)] lg:pb-28')}>
      <div className="lg:pt-6">
        <h1 className="display max-w-[13ch] text-[clamp(2.6rem,4.4vw,3.75rem)]">Read a resume the way an AI screener does.</h1>
        <p className={cn(lede, 'max-w-[42ch]')}>
          A PDF can carry text that never shows on the page: white on white, microscopic, parked outside the margin. An AI screener reads all of it,
          including instructions written for the screener and not for you.
        </p>
        <p className="mt-4 max-w-[42ch] text-[19px] leading-relaxed text-graphite">This scanner shows both readings of a file and marks where they differ.</p>
        <div className="mt-9 flex flex-wrap items-center gap-x-7 gap-y-4">
          <Button asChild className="h-12 px-6 text-base font-medium"><Link to="/scan">Scan a resume</Link></Button>
          <a href="#method" className="rounded-sm text-base underline decoration-line-strong hover:decoration-ink">How it decides</a>
        </div>
      </div>

      <div className="stage p-4 md:p-5">
        <div className="flex flex-wrap items-center justify-between gap-x-6 gap-y-2">
          <Segmented label="Page view" value={view} onChange={choose} options={VIEWS} />
          <p className="text-sm text-graphite">A real sample resume with four test attacks, scanned in {hero.seconds} seconds</p>
        </div>
        <div className="mt-4 grid gap-6 sm:grid-cols-[minmax(0,1.62fr)_minmax(0,1fr)]">
          <Sheet className="max-sm:mb-12" image={hero.image} alt="A one-page sample resume as a reader sees it" page={hero} marks={heroMarks} lines={hero.lines} program={program} sweep={sweep} />
          <div className="min-w-0 sm:pt-1" aria-live="polite">
            {program ? (
              <>
                <h2 className="text-[15px] font-semibold">In the file, not on the page</h2>
                <ol className="mt-3 space-y-4">
                  {hero.findings.map((f, i) => (
                    <li key={i} className="grid grid-cols-[22px_minmax(0,1fr)] gap-x-2.5">
                      <span className="tag">{i + 1}</span>
                      <div className="min-w-0">
                        <p className="text-[15px] font-medium leading-snug">{f.title}</p>
                        {f.technique_label && <p className="text-sm leading-snug text-graphite">{f.technique_label.charAt(0).toUpperCase() + f.technique_label.slice(1)}</p>}
                        <p className="mt-1.5 line-clamp-3 font-mono text-[12.5px] leading-normal text-select-ink [overflow-wrap:anywhere]">
                          {isInstruction(f) ? <span className="hl text-ink">{f.text}</span> : f.text}
                        </p>
                      </div>
                    </li>
                  ))}
                </ol>
              </>
            ) : (
              <>
                <h2 className="text-[15px] font-semibold">On the page</h2>
                <p className="mt-3 text-[15px] leading-relaxed text-graphite">One ordinary page: skills, experience, education. Nothing on it looks unusual, in print or on screen.</p>
                <p className="mt-3 text-[15px] leading-relaxed text-graphite">The file holds {hero.findings.length} more passages that never show.</p>
              </>
            )}
          </div>
        </div>
        <ul className={cn('mt-4 flex flex-wrap gap-x-6 gap-y-1.5 text-sm text-graphite transition-opacity', !program && 'opacity-0')} aria-hidden={!program}>
          <li className="flex items-center gap-2"><i className="h-3 w-6 rounded-[2px] bg-select/20" />Text in the file</li>
          <li className="flex items-center gap-2"><i className="h-3 w-6 rounded-[2px] bg-select-tint shadow-[0_0_0_1.5px_var(--select)]" />In the file but not printed</li>
          <li className="flex items-center gap-2"><i className="h-3 w-6 rounded-[2px] bg-marker" />Reads as an instruction</li>
        </ul>
      </div>
    </section>
  )
}

/* ------------------------------------------------------------- attack types */

const GROUPS = [
  { title: 'Hidden on the page', keys: ['white_text', 'invisible_text', 'transparent', 'tiny_font', 'off_page', 'covered', 'hidden_layer'] },
  { title: 'Printed in plain sight', keys: ['visible_text', 'zero_width', 'lookalike'] },
  { title: 'Elsewhere in the file', keys: ['metadata', 'annotation', 'image_text'] },
]
const byKey = Object.fromEntries(specimens.map((s) => [s.key, s]))

function Attacks() {
  const [key, setKey] = useState('white_text')
  const [view, setView] = useState<View>('program')
  const s = byKey[key]
  const f = s.finding
  return (
    <section id="attacks" className="border-t border-line py-20 md:py-28">
      <div className={wrap}>
        <h2 className={cn(h2, 'max-w-[18ch]')}>Thirteen ways to hide an instruction</h2>
        <p className={lede}>Each example is the same sample resume with one test attack added, then scanned. The marks and the wording are the scanner's own output.</p>

        <div className="mt-12 grid gap-x-14 gap-y-6 lg:grid-cols-[15.5rem_minmax(0,1fr)]">
          <div className="lg:hidden">
            <Select value={key} onValueChange={setKey}>
              <SelectTrigger aria-label="Attack type" className="h-11 w-full text-base"><SelectValue /></SelectTrigger>
              <SelectContent>
                {GROUPS.map((g) => (
                  <SelectGroup key={g.title}>
                    <SelectLabel>{g.title}</SelectLabel>
                    {g.keys.map((k) => <SelectItem key={k} value={k}>{byKey[k].label}</SelectItem>)}
                  </SelectGroup>
                ))}
              </SelectContent>
            </Select>
          </div>
          <div className="hidden lg:block">
            {GROUPS.map((g) => (
              <div key={g.title} className="mb-8">
                <h3 className="mb-2.5 text-sm text-graphite">{g.title}</h3>
                <ul className="border-l border-line">
                  {g.keys.map((k) => (
                    <li key={k}>
                      <button type="button" aria-pressed={k === key} onClick={() => setKey(k)}
                        className={cn('-ml-px block w-full rounded-none border-l-2 py-[7px] pl-4 pr-2 text-left text-[15px] leading-snug transition-colors',
                          k === key ? 'border-ink font-medium text-ink' : 'border-transparent text-graphite hover:text-ink')}>
                        {byKey[k].label}
                      </button>
                    </li>
                  ))}
                </ul>
              </div>
            ))}
          </div>

          <div className="min-w-0" aria-live="polite">
            <div className="stage p-4 md:p-5">
              <div className="flex flex-wrap items-center justify-between gap-x-6 gap-y-3">
                <h3 className="text-lg font-semibold tracking-[-0.005em]">{s.label}</h3>
                {s.crop && <Segmented label="Page view" value={view} onChange={setView} options={VIEWS} />}
              </div>
              {s.crop ? (
                <Sheet className="mt-4" image={s.crop.image} alt={`Part of the sample resume page with this attack added: ${s.label}`}
                  page={s.crop} top={s.crop.top} program={view === 'program'} tags={false} marks={[{ finding: f, number: 1 }]} />
              ) : (
                <p className="mt-4 bg-paper px-6 py-7 text-[17px] shadow-lift">This one sits in the document properties, in the keywords field. Nothing shows on any page.</p>
              )}
            </div>

            <div className="mt-8 grid gap-x-14 gap-y-8 md:grid-cols-2">
              <div>
                <h4 className="text-sm text-graphite">How it works</h4>
                {f.technique_label && <p className="mt-2 text-[17px] font-medium leading-snug">The text is {f.technique_label}.</p>}
                <p className="mt-2 text-[17px] leading-relaxed text-graphite">{f.explanation}</p>
              </div>
              <div>
                <h4 className="text-sm text-graphite">What the scanner reports</h4>
                <p className="mt-2 flex items-center gap-2.5 text-[17px] font-medium leading-snug">
                  <i className={cn('glyph', s.verdict)} aria-hidden="true" />
                  <span><span className={LEVEL_TEXT[s.verdict]}>{LEVELS[s.verdict]}</span>: {f.title.toLowerCase()}</span>
                </p>
                <p className={cn('extracted mt-3', f.hidden && 'hidden-text')}>{isInstruction(f) ? <span className="hl text-ink">{f.text}</span> : f.text}</p>
                {s.measured && (
                  <p className="mt-3 text-[15px] text-graphite">
                    In the held-out test, {s.measured.detected} of {s.measured.n} files carrying this attack were called an attack.
                  </p>
                )}
              </div>
            </div>
          </div>
        </div>
      </div>
    </section>
  )
}

/* ------------------------------------------------------------------- method */

const STEPS = [
  ['Render the page and read it back', 'Every page is rendered at 200 dpi, the way it prints, and read by OCR. That is the page as a person sees it.'],
  ['Compare it with what is in the file', 'The text a program extracts is compared, block by block, with what OCR saw in the same place. A block that is in the file but not on the page is hidden.'],
  ['Trace how it was hidden', 'Same colour as the background, the PDF invisible mode, full transparency, a microscopic font, placement outside the page, a shape drawn on top, or a switched-off layer.'],
  ['Score every piece of text for instructions', 'Two classifiers read the page text, the metadata, comments and form fields, and the text inside images: a public prompt-injection detector, and one fine-tuned on resume text for this project.'],
]
const VERDICTS: [Level, string][] = [
  ['attack', 'Hidden text, or an instruction whose wording shows its purpose.'],
  ['review', 'Something a person should look at: an unclear instruction, invisible characters, look-alike letters, an embedded file.'],
  ['clean', 'Nothing was flagged.'],
]

function Method() {
  const row = 'grid grid-cols-[2.75rem_minmax(0,1fr)] border-t border-line py-7'
  const number = 'font-serif text-[22px] leading-7 text-graphite tabular-nums'
  return (
    <section id="method" className="border-t border-line py-20 md:py-28">
      <div className={cn(wrap, 'grid gap-x-16 gap-y-10 lg:grid-cols-[minmax(0,5fr)_minmax(0,7fr)]')}>
        <div className="lg:sticky lg:top-10 lg:self-start">
          <h2 className={cn(h2, 'max-w-[12ch]')}>Two readings of every page</h2>
          <p className={cn(lede, 'max-w-[38ch]')}>The scanner reads each page once as a person and once as a program, and looks at what differs. It runs on this computer in a few seconds per file.</p>
        </div>
        <ol className="border-b border-line">
          {STEPS.map(([title, text], i) => (
            <li key={title} className={row}>
              <span className={number} aria-hidden="true">{i + 1}</span>
              <div>
                <h3 className="text-[19px] font-semibold leading-7 tracking-[-0.005em]">{title}</h3>
                <p className="mt-1.5 max-w-[60ch] text-[17px] leading-relaxed text-graphite">{text}</p>
              </div>
            </li>
          ))}
          <li className={row}>
            <span className={number} aria-hidden="true">5</span>
            <div>
              <h3 className="text-[19px] font-semibold leading-7 tracking-[-0.005em]">Give one of three verdicts</h3>
              <dl className="mt-3 space-y-2.5">
                {VERDICTS.map(([level, when]) => (
                  <div key={level} className="grid grid-cols-[1.25rem_9.5rem_minmax(0,1fr)] items-baseline gap-x-1 text-[17px] max-sm:grid-cols-[1.25rem_minmax(0,1fr)]">
                    <i className={cn('glyph translate-y-px', level)} aria-hidden="true" />
                    <dt className={cn('font-medium', LEVEL_TEXT[level])}>{LEVELS[level]}</dt>
                    <dd className="leading-relaxed text-graphite max-sm:col-start-2">{when}</dd>
                  </div>
                ))}
              </dl>
            </div>
          </li>
        </ol>
      </div>
    </section>
  )
}

/* ------------------------------------------------------------------ results */

const CHART = { attack: 'var(--attack)', review: '#d99a1c', clean: '#2a9463', missed: '#9aa2ab' }

function Segments({ label, total, parts }: { label: string; total: number; parts: { n: number; text: string; color: string }[] }) {
  return (
    <div>
      <p className="text-[15px] font-medium">{label}</p>
      <div className="mt-2.5 flex h-3 gap-[2px]" role="img" aria-label={`${label}: ${parts.map((p) => `${p.n} ${p.text}`).join(', ')}`}>
        {parts.filter((p) => p.n > 0).map((p) => <div key={p.text} className="min-w-1 first:rounded-l-full last:rounded-r-full" style={{ flex: `${p.n} 0 0`, background: p.color }} />)}
      </div>
      <ul className="mt-3 space-y-1 text-[15px]">
        {parts.map((p) => (
          <li key={p.text} className="grid grid-cols-[10px_2.25rem_minmax(0,1fr)_3.25rem] items-baseline gap-x-2.5">
            <span className="size-2.5 translate-y-px rounded-full" style={{ background: p.color }} aria-hidden="true" />
            <span className="text-right font-medium tabular-nums">{p.n}</span>
            <span>{p.text}</span>
            <span className="text-right text-graphite tabular-nums">{pct(p.n, total)}</span>
          </li>
        ))}
      </ul>
    </div>
  )
}

function Results() {
  const e = evaluation
  const v = e.clean_verdicts
  const first = experiment.configs[0], last = experiment.configs[experiment.configs.length - 1]
  const labels = Object.fromEntries(experiment.configs.map((c) => [c.key, c.label]))
  const h3 = 'title text-[26px]'
  const caption = 'mt-6 max-w-[62ch] text-sm leading-relaxed text-graphite'
  return (
    <section id="results" className="border-t border-line py-20 md:py-28">
      <div className={wrap}>
        <h2 className={h2}>What was measured</h2>
        <p className={lede}>Two questions, tested separately. Does removing the flagged text protect a real AI screener? And does the scanner find attacks it has not seen before?</p>

        <div className="mt-14 grid gap-x-16 gap-y-16 lg:grid-cols-2">
          <figure>
            <h3 className={h3}>Attacks that changed a real model's decision</h3>
            <p className="mt-3 max-w-[52ch] text-[17px] leading-relaxed text-graphite">
              Removing both the hidden text and the instructions cut the attacks that flipped the decision from {first.successes} of {first.eligible} to {last.successes} of {last.eligible}.
            </p>
            <ul className="mt-7">
              {experiment.configs.map((c) => (
                <li key={c.key} className="grid grid-cols-[minmax(0,1fr)_auto] items-baseline gap-x-4 border-t border-line py-3.5 last:border-b">
                  <span className={cn('text-[15px]', c === last && 'font-semibold')}>{c.label}</span>
                  <span className="text-[15px] tabular-nums"><span className="font-medium">{c.successes} of {c.eligible}</span> <span className="inline-block w-14 text-right text-graphite">{pct(c.successes, c.eligible)}</span></span>
                  <span className="col-span-2 mt-2 block h-2 rounded-full bg-desk">
                    <span className="block h-full rounded-full bg-ink" style={{ width: `${(100 * c.successes) / c.eligible}%` }} />
                  </span>
                  <span className={cn('col-span-2 mt-2 text-sm', c.clean_agreement < 1 ? 'text-attack' : 'text-graphite')}>Clean resumes that kept their decision: {pct(c.clean_agreement, 1)}</span>
                </li>
              ))}
            </ul>
            <figcaption className={caption}>
              {experiment.model} scored {experiment.resumes} real resumes against a junior Python backend rubric. The {experiment.rejected_resumes} it rejected were each given {experiment.attacks_each} attacks
              ({experiment.placements} placements, {experiment.wordings} wordings), making {first.eligible} trials per defence. An attack succeeds when the decision flips to select. A small sample: it does not establish hiring safety.
            </figcaption>
          </figure>

          {ablation && (
            <figure>
              <h3 className={h3}>Which attacks got through each defence</h3>
              <p className="mt-3 max-w-[52ch] text-[17px] leading-relaxed text-graphite">
                Each check closes the gap the other leaves. What survives both is an instruction that is printed in plain sight and worded like a reviewer's note.
              </p>
              <div className="mt-7 overflow-x-auto">
                <table className="w-full min-w-[30rem] border-separate border-spacing-[3px] text-[15px]">
                  <thead>
                    <tr>
                      <th className="w-[38%]" />
                      {ablation.columns.map((c) => <th key={c} scope="col" className="pb-1.5 text-left align-bottom text-sm font-normal leading-tight text-graphite">{c}</th>)}
                    </tr>
                  </thead>
                  <tbody>
                    {ablation.rows.map((r) => (
                      <tr key={r.key}>
                        <th scope="row" className={cn('pr-3 text-left font-normal leading-snug', r.key === last.key && 'font-semibold')}>{labels[r.key]}</th>
                        {r.cells.map((cell, i) => {
                          const share = cell.s / cell.n
                          return (
                            <td key={i} className={cn('h-11 rounded-[3px] px-3 tabular-nums', share > 0.5 ? 'text-white' : share > 0 ? 'text-ink' : 'text-graphite')}
                              style={{ background: share > 0 ? `color-mix(in srgb, var(--attack) ${Math.round(18 + 82 * share)}%, white)` : 'var(--desk)' }}>
                              {cell.s} of {cell.n}
                            </td>
                          )
                        })}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
              <figcaption className={caption}>
                Attacks that succeeded, out of those tried. Hidden means white or invisible text. Direct is “Ignore the job rubric…”; reworded is the same request written as reviewer guidance, with no override wording.
              </figcaption>
            </figure>
          )}

          <figure className="lg:col-span-2">
            <div className="grid gap-x-16 gap-y-8 lg:grid-cols-2">
              <div>
                <h3 className={h3}>The scanner on files it had not seen</h3>
                <p className="mt-3 max-w-[52ch] text-[17px] leading-relaxed text-graphite">
                  All {e.hidden_found} of the {e.hidden_attacks} hidden-text attacks were called an attack. The misses and reviews are instructions printed in plain sight or placed in metadata, comments and images, in unusual wording.
                </p>
                <figcaption className={caption}>
                  Measured on scanner version {e.scanner_version}{e.scanner_version !== evidence.scanner_version ? ` (this is version ${evidence.scanner_version})` : ''}, on resumes and attack wordings kept out of its development. Mean time per file: {e.mean_seconds} seconds.
                </figcaption>
              </div>
              <div className="grid gap-x-10 gap-y-8 sm:grid-cols-2 lg:pt-2">
                <Segments label={`${e.attacks} resumes with an attack added`} total={e.attacks} parts={[
                  { n: e.called_attack, text: 'called an attack', color: CHART.attack },
                  { n: e.flagged - e.called_attack, text: 'sent for review', color: CHART.review },
                  { n: e.attacks - e.flagged, text: 'missed', color: CHART.missed },
                ]} />
                <Segments label={`${e.clean} clean resumes`} total={e.clean} parts={[
                  { n: v.clean, text: 'passed', color: CHART.clean },
                  { n: v.review, text: 'sent for review', color: CHART.review },
                  { n: v.attack, text: 'wrongly called an attack', color: CHART.attack },
                ]} />
              </div>
            </div>
          </figure>
        </div>
      </div>
    </section>
  )
}

